# 3. BLOCK DEFINITION & SCHEMA
# ==============================================================================
class SentinelBlock:
    def __init__(
        self,
        block_index: int,
        timestamp: str,
        transactions: List[Dict[str, Any]],
        merkle_root: str,
        previous_block_hash: str,
        validator_node_id: str,
        validator_signature: str,
        block_hash: str,
    ):
        self.block_index = block_index
        self.timestamp = timestamp
        self.transactions = transactions
        self.merkle_root = merkle_root
        self.previous_block_hash = previous_block_hash
        self.validator_node_id = validator_node_id
        self.validator_signature = validator_signature
        self.block_hash = block_hash

    def to_dict(self) -> Dict[str, Any]:
        return {
            "block_index": self.block_index,
            "timestamp": self.timestamp,
            "transactions": self.transactions,
            "merkle_root": self.merkle_root,
            "previous_block_hash": self.previous_block_hash,
            "validator_node_id": self.validator_node_id,
            "validator_signature": self.validator_signature,
            "block_hash": self.block_hash,
        }

    def __getitem__(self, key: str) -> Any:
        return getattr(self, key)

    @staticmethod
    def calculate_header_hash(
        block_index: int,
        timestamp: str,
        merkle_root: str,
        previous_block_hash: str,
        validator_node_id: str,
    ) -> str:
        header_str = f"{block_index}:{timestamp}:{merkle_root}:{previous_block_hash}:{validator_node_id}"
        return hashlib.sha256(header_str.encode("utf-8")).hexdigest()


