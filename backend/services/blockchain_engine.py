def compute_transaction_hash(tx: Dict[str, Any]) -> str:
    """Computes canonical deterministic SHA-256 hash for a transaction payload."""
    canonical_json = json.dumps(tx, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()


def build_merkle_root(transactions: List[Dict[str, Any]]) -> str:
    """
    Computes a cryptographic binary Merkle Root from transaction list.
    Handles odd leaves by duplicating the terminal leaf.
    """
    if not transactions:
        return "0" * 64

    hashes = [compute_transaction_hash(tx) for tx in transactions]

    while len(hashes) > 1:
        if len(hashes) % 2 != 0:
            hashes.append(hashes[-1])
        next_level = []
        for i in range(0, len(hashes), 2):
            combined = (hashes[i] + hashes[i + 1]).encode("utf-8")
            next_level.append(hashlib.sha256(combined).hexdigest())
        hashes = next_level

    return hashes[0]


