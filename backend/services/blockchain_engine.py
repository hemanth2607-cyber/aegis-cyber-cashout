def sign_payload(payload_bytes: bytes, private_key: str) -> str:
    """Computes an institutional cryptographic signature over the payload."""
    return hmac.new(private_key.encode("utf-8"), payload_bytes, hashlib.sha256).hexdigest()


def verify_signature(payload_bytes: bytes, signature: str, node_id_or_key: str) -> bool:
    """Verifies that the signature was generated by the authorized consortium node (by node_id or public_key)."""
    node = CONSORTIUM_NODES.get(node_id_or_key)
    if not node:
        for n in CONSORTIUM_NODES.values():
            if n["public_key"] == node_id_or_key:
                node = n
                break
    if not node:
        return False
    expected = hmac.new(node["private_key"].encode("utf-8"), payload_bytes, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, signature)


