    def tamper_test_mutation(self, block_index: int = 1, field: str = "amount", new_value: Any = 99999999.0) -> Dict[str, Any]:
        """
        Deliberately mutates data inside a past block without re-mining or forging signatures.
        Instantly demonstrates to judges that Merkle root and hash verification break.
        """
        if block_index >= len(self.chain):
            raise IndexError(f"Block index {block_index} out of range (chain length: {len(self.chain)})")

        target_block = self.chain[block_index]
        if target_block.transactions:
            original_tx = json.loads(json.dumps(target_block.transactions[0]))
            target_block.transactions[0][field] = new_value
            target_block.transactions[0]["TAMPER_ALERT"] = "UNAUTHORIZED_DATABASE_MUTATION_INJECTED"
        else:
            original_tx = {}
            target_block.transactions.append({"TAMPER_INJECTION": "FORGED_RECORD"})

        return {
            "is_tampered": True,
            "tampered_block_index": block_index,
            "original_state": original_tx,
            "mutated_field": field,
            "new_value": new_value,
            "verification_after_tamper": self.verify_chain_integrity(),
        }

