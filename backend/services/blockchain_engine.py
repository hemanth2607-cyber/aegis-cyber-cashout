    # --------------------------------------------------------------------------
    # Block Mining & PoA Consensus
    # --------------------------------------------------------------------------
    def mine_block(self, validator_node_id: str = "I4C_CENTRAL_ORACLE") -> Optional[Dict[str, Any]]:
        """
        Mines a new block containing all pending transactions using PoA consensus.
        Enforces cryptographic validator identity and sub-10ms latency.
        """
        if validator_node_id not in CONSORTIUM_NODES:
            raise ValueError(f"Unauthorized validator node: {validator_node_id}")

        if not self.pending_transactions:
            # If no pending transactions, create an empty heartbeat state
            txs_to_mine = [{
                "event_type": "CONSORTIUM_HEARTBEAT",
                "validator": validator_node_id,
                "timestamp": datetime.now(timezone.utc).isoformat()
            }]
        else:
            txs_to_mine = list(self.pending_transactions)
            self.pending_transactions.clear()

        block_index = len(self.chain)
        timestamp = datetime.now(timezone.utc).isoformat()
        previous_block_hash = self.chain[-1].block_hash
        merkle_root = build_merkle_root(txs_to_mine)

        header_hash = PraharBlock.calculate_header_hash(
            block_index, timestamp, merkle_root, previous_block_hash, validator_node_id
        )

        private_key = CONSORTIUM_NODES[validator_node_id]["private_key"]
        signature = sign_payload(header_hash.encode("utf-8"), private_key)

        new_block = PraharBlock(
            block_index=block_index,
            timestamp=timestamp,
            transactions=txs_to_mine,
            merkle_root=merkle_root,
            previous_block_hash=previous_block_hash,
            validator_node_id=validator_node_id,
            validator_signature=signature,
            block_hash=header_hash,
        )

        self.chain.append(new_block)
        return new_block

    # --------------------------------------------------------------------------
    # Cryptographic Chain Verification Engine
    # --------------------------------------------------------------------------
    def verify_chain_integrity(self) -> Dict[str, Any]:
        """
        Iterates over the entire blockchain, validating:
        1. Previous block hash linking.
        2. Merkle Root integrity against transaction leaves.
        3. Block Header SHA-256 hash.
        4. Validator node signature using public key verification.
        """
        if not self.chain:
            return {
                "is_valid": False,
                "block_count": 0,
                "chain_status": "EMPTY_CHAIN",
                "bsa_sec_63_compliance": "INVALID",
                "tampered_block": None,
                "error": "No blocks in chain",
            }

        # Validate Genesis Block
        genesis = self.chain[0]
        if genesis.block_index != 0 or genesis.previous_block_hash != "0" * 64:
            return {
                "is_valid": False,
                "block_count": len(self.chain),
                "chain_status": "COMPROMISED_GENESIS",
                "bsa_sec_63_compliance": "INVALID",
                "tampered_block": 0,
                "error": "Genesis block structure is invalid",
            }

        # Iterate all blocks
        for i in range(len(self.chain)):
            current = self.chain[i]

            # 1. Verify previous hash link (for blocks > 0)
            if i > 0:
                prev = self.chain[i - 1]
                if current.previous_block_hash != prev.block_hash:
                    return {
                        "is_valid": False,
                        "block_count": len(self.chain),
                        "chain_status": "CRYPTOGRAPHIC_INTEGRITY_VIOLATION",
                        "violation_type": "BROKEN_HASH_LINK",
                        "bsa_sec_63_compliance": "INVALID",
                        "tampered_block": i,
                        "broken_links": [i],
                        "error": f"Block {i} previous_block_hash does not match Block {i-1} block_hash",
                        "reason": f"Previous hash link mismatch at block {i}",
                    }

            # 2. Verify Merkle Root
            calculated_merkle = build_merkle_root(current.transactions)
            if calculated_merkle != current.merkle_root:
                return {
                    "is_valid": False,
                    "block_count": len(self.chain),
                    "chain_status": "CRYPTOGRAPHIC_INTEGRITY_VIOLATION",
                    "violation_type": "MERKLE_ROOT_CORRUPTED",
                    "bsa_sec_63_compliance": "INVALID",
                    "tampered_block": i,
                    "broken_links": [i],
                    "error": f"Block {i} Merkle root calculation mismatch",
                    "reason": f"Merkle root mismatch at block {i} (leaf mutation detected)",
                }

            # 3. Verify Header Hash
            calculated_hash = PraharBlock.calculate_header_hash(
                current.block_index,
                current.timestamp,
                current.merkle_root,
                current.previous_block_hash,
                current.validator_node_id,
            )
            if calculated_hash != current.block_hash:
                return {
                    "is_valid": False,
                    "block_count": len(self.chain),
                    "chain_status": "CRYPTOGRAPHIC_INTEGRITY_VIOLATION",
                    "violation_type": "BLOCK_HEADER_MUTATED",
                    "bsa_sec_63_compliance": "INVALID",
                    "tampered_block": i,
                    "broken_links": [i],
                    "error": f"Block {i} header hash does not match computed SHA-256",
                    "reason": f"Header hash mismatch at block {i}",
                }

            # 4. Verify Validator Signature
            is_sig_valid = verify_signature(
                current.block_hash.encode("utf-8"),
                current.validator_signature,
                current.validator_node_id,
            )
            if not is_sig_valid:
                return {
                    "is_valid": False,
                    "block_count": len(self.chain),
                    "chain_status": "CRYPTOGRAPHIC_INTEGRITY_VIOLATION",
                    "violation_type": "INVALID_VALIDATOR_SIGNATURE",
                    "bsa_sec_63_compliance": "INVALID",
                    "tampered_block": i,
                    "broken_links": [i],
                    "error": f"Block {i} has forged or invalid signature for validator {current.validator_node_id}",
                    "reason": f"Validator signature invalid at block {i}",
                }

        return {
            "is_valid": True,
            "block_count": len(self.chain),
            "chain_status": "SECURE_UNBROKEN",
            "bsa_sec_63_compliance": "VALID",
            "tampered_block": None,
            "broken_links": [],
            "error": None,
            "reason": None,
            "consensus": "PoA_CONSORTIUM_MHA_NPCI_POLICE",
        }

    # --------------------------------------------------------------------------
    # Interactive Tamper Demonstration for Judges
